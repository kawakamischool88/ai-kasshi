/** すでに提案済みの候補があるときに足す指示（同じ内容を繰り返さないため） */
export function alreadySuggestedInstruction(texts: string[]): string {
  if (texts.length === 0) return "";
  return `
【すでにこの会話で提案済みの記憶】
次の内容は、すでに本人へ提示して処理が済んでいます。
**同じ内容・似た内容を、もう一度取り出してはいけません。**

${texts.map((t) => `- ${t}`).join("\n")}`;
}

/**
 * 本人がはっきり保存を希望しているか。
 *
 * AI任せにせず、ここで確実に拾う。
 * （AIが値打ちなしと判断して候補を作らない、という取りこぼしを防ぐため）
 */
const SAVE_REQUEST_PATTERNS = [
  "覚えておいて",
  "覚えといて",
  "記憶しておいて",
  "残しておいて",
  "これは残して",
  "忘れないで",
  "忘れないように",
  "カッシーに残して",
  "メモしておいて",
  "記録しておいて",
];

export function isSaveRequest(text: string): boolean {
  // 音声入力では語の間に空白が入ることがあるため、空白を取り除いてから探す
  const normalized = text.replace(/[\s　]/g, "");
  return SAVE_REQUEST_PATTERNS.some((p) => normalized.includes(p));
}
